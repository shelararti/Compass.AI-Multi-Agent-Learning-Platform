"""
Evaluation Agent.

Handles two shapes of work, distinguished by which fields the client sent:
- Quiz grading: deterministic (no LLM call needed) -- we already know the
  correct_index for each question, so it's a straight comparison.
- Code grading: LLM-graded against the rubric generated by the Coding Agent.

Produces a normalized {"score": int, "feedback": str, "details": {...}}
regardless of which path was taken, so the Memory node and the client
don't need to branch on quiz-vs-code.
"""

from .. import llm_client
from .. import knowledge_base


def _subject_title_for(state: dict) -> str:
    """Evaluation runs as its own graph stage, so it doesn't go through the
    orchestrator's subject resolution -- look it up from topic_id directly."""
    subject_title = state.get("subject_title")
    if subject_title:
        return subject_title
    topic = knowledge_base.get_topic(state.get("topic_id", ""))
    if topic and topic.get("subject_id"):
        subject = knowledge_base.get_subject(topic["subject_id"])
        if subject:
            return subject["title"]
    return "your course"


def _grade_quiz(state: dict) -> dict:
    questions = state.get("quiz_questions") or []
    answers = state.get("quiz_answers") or []

    if not questions:
        return {"error": "No quiz questions supplied to grade."}

    results = []
    correct_count = 0
    for i, q in enumerate(questions):
        picked = answers[i] if i < len(answers) else None
        is_correct = picked == q.get("correct_index")
        if is_correct:
            correct_count += 1
        results.append(
            {
                "question": q.get("question"),
                "picked_index": picked,
                "correct_index": q.get("correct_index"),
                "correct": is_correct,
                "explanation": q.get("explanation"),
            }
        )

    total = len(questions)
    score = round(100 * correct_count / total) if total else 0
    return {
        "evaluation": {
            "score": score,
            "feedback": f"Scored {correct_count}/{total} on this quiz.",
            "details": {"kind": "quiz", "results": results, "correct": correct_count, "total": total},
        }
    }


def _grade_code(state: dict) -> dict:
    task = state.get("code_task_description", "")
    rubric = state.get("code_rubric") or []
    submission = state.get("code_submission", "")

    if not submission.strip():
        return {"error": "No code submission supplied to grade."}

    subject_title = _subject_title_for(state)
    grade_system = (
        f"You are a rigorous but encouraging grader for a course on "
        f"{subject_title}. Respond with ONLY valid JSON, no markdown fences, no extra text."
    )

    user = (
        f"Task given to the student: {task}\n"
        f"Rubric: {'; '.join(rubric)}\n"
        f"Student's submission:\n{submission}\n\n"
        "Grade the submission against the rubric. Return this exact JSON shape:\n"
        '{"score":0,"strengths":["..."],"improvements":["..."],'
        '"feedback":"one encouraging overall sentence"}'
    )
    try:
        result = llm_client.call_llm_json(grade_system, user)
    except Exception as e:
        return {"error": f"Could not grade the submission: {e}"}

    # Defensive clamp: nothing upstream guarantees the model returns 0-100.
    raw_score = result.get("score", 0)
    try:
        score = max(0, min(100, int(raw_score)))
    except (TypeError, ValueError):
        score = 0

    return {
        "evaluation": {
            "score": score,
            "feedback": result.get("feedback", ""),
            "details": {
                "kind": "code",
                "strengths": result.get("strengths", []),
                "improvements": result.get("improvements", []),
            },
        }
    }


def evaluation_node(state: dict) -> dict:
    if state.get("quiz_questions") is not None:
        return _grade_quiz(state)
    if state.get("code_submission") is not None:
        return _grade_code(state)
    return {"error": "Evaluation stage reached without quiz or code data to grade."}
